import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { writeFileSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { setup, root, shim, events } from '../../../scripts/fixture/runtime.mjs';
const dir = root + '/artifacts/P1/package/smoke';
const entry = root + '/artifacts/P1/package/extracted/package/src/index.ts';
const { env, args } = setup(dir);
args[args.indexOf(root + '/src/index.ts')] = entry;
const child = spawn(shim, [...args, '--print', '--mode', 'json', 'CURRENT_INPUT_MARKER packaged entry'], { env, cwd: dir + '/cwd', stdio: ['ignore', 'pipe', 'pipe'] });
let stdout = '', stderr = '';
child.stdout.on('data', data => stdout += data);
child.stderr.on('data', data => stderr += data);
const code = await new Promise(resolve => child.on('exit', resolve));
writeFileSync(dir + '/stdout.jsonl', stdout);
writeFileSync(dir + '/stderr.txt', stderr);
assert.equal(code, 0);
assert.equal(events(dir).filter(event => event.event === 'normal-request').length, 1);
assert(events(dir).find(event => event.event === 'ready').extensions.includes(entry));
assert(events(dir).find(event => event.event === 'ready').managed);
assert.equal(events(dir).find(event => event.event === 'agent_settled').outcome, 'stop');
const tarball = root + '/artifacts/P1/package/pi-compact-0.1.0.tgz';
writeFileSync(root + '/artifacts/P1/package/result.json', JSON.stringify({ code, pid: child.pid, entry, tarball, sha256: createHash('sha256').update(readFileSync(tarball)).digest('hex'), ordinaryLoader: true, realServiceRequests: 0 }, null, 2));
console.log('Packaged ordinary extension passed the real installed shim.');
